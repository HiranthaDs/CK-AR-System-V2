import type { jsPDF } from 'jspdf'
import type { CompanyProfile } from '../types/api'

export const CK_INVOICE_DETAILS = {
  name: 'CK Plastic',
  address: 'No. 242/A, Gorokgoda, Millewa, Harana, Sri Lanka.',
  phone: '0774881490 / 0712374024',
  email: 'info@ckplasticsl.com',
} as const

export function invoiceCompany(company?: Partial<CompanyProfile> | null) {
  return {
    name: company?.name?.trim() || CK_INVOICE_DETAILS.name,
    address: company?.address?.trim() || CK_INVOICE_DETAILS.address,
    phone: company?.phone?.trim() || CK_INVOICE_DETAILS.phone,
    email: company?.email?.trim() || CK_INVOICE_DETAILS.email,
    logo_url: company?.logo_url?.trim() || null,
  }
}

export async function invoiceLogoDataUrl(url: string | null | undefined) {
  if (!url) return null
  try {
    const response = await fetch(url, { mode: 'cors', credentials: 'omit' })
    if (!response.ok) return null
    const blob = await response.blob()
    return await new Promise<string | null>((resolve) => {
      const reader = new FileReader()
      reader.onload = () => resolve(typeof reader.result === 'string' ? reader.result : null)
      reader.onerror = () => resolve(null)
      reader.readAsDataURL(blob)
    })
  } catch {
    return null
  }
}

export function drawInvoiceHeader(document: jsPDF, options: {
  company: ReturnType<typeof invoiceCompany>
  logo: string | null
  title: string
  number: string
}) {
  const { company, logo, title, number } = options
  const width = document.internal.pageSize.getWidth()
  const margin = 14
  document.setFillColor(17, 42, 92)
  document.rect(0, 0, width, 43, 'F')
  let companyX: number
  if (logo) {
    try {
      const format = logo.startsWith('data:image/jpeg') ? 'JPEG' : logo.startsWith('data:image/webp') ? 'WEBP' : 'PNG'
      document.addImage(logo, format, margin, 8, 24, 24, undefined, 'FAST')
      companyX = 43
    } catch {
      companyX = margin
    }
  } else {
    document.setFillColor(36, 87, 214)
    document.roundedRect(margin, 8, 24, 24, 3, 3, 'F')
    document.setTextColor(255, 255, 255)
    document.setFont('helvetica', 'bold')
    document.setFontSize(12)
    document.text('CK', margin + 12, 23, { align: 'center' })
    companyX = 43
  }
  document.setTextColor(255, 255, 255)
  document.setFont('helvetica', 'bold')
  document.setFontSize(17)
  document.text(company.name, companyX, 13)
  document.setFont('helvetica', 'normal')
  document.setFontSize(7.2)
  document.text([company.address, `${company.phone}  |  ${company.email}`], companyX, 19, { maxWidth: 105 })
  document.setFont('helvetica', 'bold')
  document.setFontSize(16)
  document.text(title, width - margin, 15, { align: 'right' })
  document.setFontSize(9)
  document.text(number, width - margin, 24, { align: 'right' })
}

export function drawInvoiceFooters(document: jsPDF, number: string) {
  const width = document.internal.pageSize.getWidth()
  const height = document.internal.pageSize.getHeight()
  const margin = 14
  const pages = document.getNumberOfPages()
  for (let page = 1; page <= pages; page += 1) {
    document.setPage(page)
    document.setDrawColor(220, 226, 235)
    document.line(margin, height - 19, width - margin, height - 19)
    document.setFont('helvetica', 'bold')
    document.setFontSize(7)
    document.setTextColor(58, 72, 96)
    document.text('Thank you for your business.', margin, height - 13)
    document.setFont('helvetica', 'normal')
    document.setFontSize(6.5)
    document.setTextColor(102, 112, 133)
    document.text(`${number}  |  Generated by CK SYS`, margin, height - 8)
    document.text(`Page ${page} of ${pages}`, width - margin, height - 8, { align: 'right' })
  }
}

export function downloadInvoiceBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  anchor.rel = 'noopener'
  document.body.appendChild(anchor)
  anchor.click()
  anchor.remove()
  window.setTimeout(() => URL.revokeObjectURL(url), 0)
}

export async function openInvoicePdf(createBlob: () => Promise<Blob>) {
  const popup = window.open('', '_blank')
  if (!popup) return false
  popup.opener = null
  popup.document.write('<!doctype html><title>Preparing PDF</title><p style="font:16px system-ui;padding:24px">Preparing PDF…</p>')
  popup.document.close()
  try {
    const url = URL.createObjectURL(await createBlob())
    popup.location.replace(url)
    window.setTimeout(() => URL.revokeObjectURL(url), 60_000)
    return true
  } catch (error) {
    popup.close()
    throw error
  }
}
